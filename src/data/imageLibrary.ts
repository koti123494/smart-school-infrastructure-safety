export const getProblemCategoryImage = (category?: string) => {
  if (!category) return schoolImages.fallback;
  return problemImages[category] || problemImages.Other || schoolImages.fallback;
};

export const getLocationImage = (locationType?: string) => {
  if (!locationType) return schoolImages.campusHero;
  return surroundingsImages[locationType] || schoolImages.campusHero;
};

export const getClassroomImage = (roomNumber?: string) => {
  if (!roomNumber) return classroomImages.default;
  const fallback = Object.entries(classroomImages).find(([key]) => roomNumber.includes(key));
  return fallback ? fallback[1] : classroomImages.default;
};
